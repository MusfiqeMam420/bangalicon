const Release = require("../models/release.model");

const parseTags = (rawTags) => {
  if (Array.isArray(rawTags)) {
    return rawTags.map((tag) => String(tag).trim()).filter(Boolean);
  }

  return String(rawTags || "")
    .split(",")
    .map((tag) => tag.trim())
    .filter(Boolean);
};

const normalizeReleaseText = (value) =>
  String(value || "")
    .normalize("NFKC")
    .replace(/[\u200B-\u200D\uFEFF]/g, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

const areReleaseTextsEquivalent = (first, second) => {
  const normalizedFirst = normalizeReleaseText(first);
  const normalizedSecond = normalizeReleaseText(second);

  if (!normalizedFirst || !normalizedSecond) {
    return normalizedFirst === normalizedSecond;
  }

  return (
    normalizedFirst === normalizedSecond ||
    normalizedFirst.startsWith(normalizedSecond) ||
    normalizedSecond.startsWith(normalizedFirst)
  );
};

const formatEntry = (entry = {}) => {
  const title = entry.title || "";
  const description = entry.description || "";
  const shouldHideDuplicateDescription =
    entry.type !== "add" && areReleaseTextsEquivalent(title, description);

  return {
  type: entry.type || "update",
  title,
  description: shouldHideDuplicateDescription ? "" : description,
  tags: Array.isArray(entry.tags) ? entry.tags : [],
  imageUrl: entry.imageUrl || "",
  autoGenerated: Boolean(entry.autoGenerated),
  groupDate: entry.groupDate || "",
  previewItems: Array.isArray(entry.previewItems)
    ? entry.previewItems
        .map((item) => ({
          label: String(item?.label || "").trim(),
          imageUrl: String(item?.imageUrl || "").trim(),
        }))
        .filter((item) => item.label)
    : [],
  };
};

const isLegacyAutoAddEntry = (entry = {}) =>
  entry?.type === "add" &&
  typeof entry?.title === "string" &&
  /^Added\s+/i.test(entry.title) &&
  typeof entry?.description === "string" &&
  /is now available in the Bangalicon library\./i.test(entry.description);

const getLegacyAddName = (entry = {}) => {
  const titleMatch = String(entry?.title || "").match(/^Added\s+(.+)$/i);
  if (titleMatch?.[1]) {
    return titleMatch[1].trim();
  }

  const descriptionMatch = String(entry?.description || "").match(/^(.+?)\s+is now available/i);
  return descriptionMatch?.[1]?.trim() || "";
};

const normalizeReleaseEntries = (entries = []) => {
  const result = [];
  let groupedLegacyAdd = null;

  entries.forEach((entry) => {
    if (entry?.type === "add" && entry?.autoGenerated && Array.isArray(entry?.previewItems) && entry.previewItems.length) {
      result.push(entry);
      return;
    }

    if (!isLegacyAutoAddEntry(entry)) {
      groupedLegacyAdd = null;
      result.push(entry);
      return;
    }

    const iconName = getLegacyAddName(entry);
    if (!iconName) {
      result.push(entry);
      return;
    }

    if (!groupedLegacyAdd) {
      groupedLegacyAdd = {
        type: "add",
        title: "Added 1 icon",
        description: "Added 1 icon",
        tags: [iconName],
        imageUrl: entry.imageUrl || "",
        autoGenerated: true,
        groupDate: "",
        previewItems: [
          {
            label: iconName,
            imageUrl: entry.imageUrl || "",
          },
        ],
      };
      result.push(groupedLegacyAdd);
      return;
    }

    const existingNames = new Set(
      (groupedLegacyAdd.previewItems || []).map((item) => String(item?.label || "").trim()).filter(Boolean)
    );

    if (!existingNames.has(iconName)) {
      groupedLegacyAdd.previewItems.push({
        label: iconName,
        imageUrl: entry.imageUrl || "",
      });
      groupedLegacyAdd.tags.push(iconName);
    }

    const count = groupedLegacyAdd.previewItems.length;
    groupedLegacyAdd.title = `Added ${count} icons`;
    groupedLegacyAdd.description = `Added ${count} icons`;
    groupedLegacyAdd.imageUrl =
      groupedLegacyAdd.previewItems[groupedLegacyAdd.previewItems.length - 1]?.imageUrl || groupedLegacyAdd.imageUrl;
  });

  return result;
};

const formatRelease = (release) => ({
  id: String(release._id),
  version: release.version,
  monthLabel: release.monthLabel,
  entries: Array.isArray(release.entries)
    ? normalizeReleaseEntries(release.entries).map(formatEntry)
    : [],
  createdAt: release.createdAt || null,
  updatedAt: release.updatedAt || null,
});

exports.getAll = async (req, res) => {
  try {
    const releases = await Release.find().sort({ createdAt: -1 }).lean();
    res.json(releases.map(formatRelease));
  } catch (error) {
    res.status(500).json({ message: error.message || "Could not load release notes" });
  }
};

exports.create = async (req, res) => {
  const { version, monthLabel, type, title, description, tags, imageUrl, autoGenerated, groupDate, previewItems } = req.body || {};

  if (!String(version || "").trim()) {
    return res.status(400).json({ message: "Version is required" });
  }

  if (!String(monthLabel || "").trim()) {
    return res.status(400).json({ message: "Month label is required" });
  }

  if (!String(title || "").trim()) {
    return res.status(400).json({ message: "Note title is required" });
  }

  if (!String(description || "").trim()) {
    return res.status(400).json({ message: "Description is required" });
  }

  try {
    const normalizedVersion = String(version).trim();
    const normalizedMonth = String(monthLabel).trim();
    const entry = {
      type: ["add", "fix", "update"].includes(String(type)) ? String(type) : "update",
      title: String(title).trim(),
      description: String(description).trim(),
      tags: parseTags(tags),
      imageUrl: String(imageUrl || "").trim(),
      autoGenerated: Boolean(autoGenerated),
      groupDate: String(groupDate || "").trim(),
      previewItems: Array.isArray(previewItems)
        ? previewItems
            .map((item) => ({
              label: String(item?.label || "").trim(),
              imageUrl: String(item?.imageUrl || "").trim(),
            }))
            .filter((item) => item.label)
        : [],
    };

    let release = await Release.findOne({ version: normalizedVersion });

    if (release) {
      release.monthLabel = normalizedMonth;
      release.entries.push(entry);
      await release.save();
    } else {
      release = await Release.create({
        version: normalizedVersion,
        monthLabel: normalizedMonth,
        entries: [entry],
      });
    }

    res.status(201).json(formatRelease(release));
  } catch (error) {
    res.status(500).json({ message: error.message || "Could not save release note" });
  }
};

exports.update = async (req, res) => {
  const { id } = req.params;
  const { version, monthLabel, entries } = req.body || {};

  if (!String(version || "").trim()) {
    return res.status(400).json({ message: "Version is required" });
  }

  if (!String(monthLabel || "").trim()) {
    return res.status(400).json({ message: "Month label is required" });
  }

  try {
    const release = await Release.findById(id);

    if (!release) {
      return res.status(404).json({ message: "Release note not found" });
    }

    release.version = String(version).trim();
    release.monthLabel = String(monthLabel).trim();
    release.entries = Array.isArray(entries)
      ? entries
          .map((entry) => ({
            type: ["add", "fix", "update"].includes(String(entry?.type)) ? String(entry.type) : "update",
            title: String(entry?.title || "").trim(),
            description: String(entry?.description || "").trim(),
            tags: parseTags(entry?.tags),
            imageUrl: String(entry?.imageUrl || "").trim(),
            autoGenerated: Boolean(entry?.autoGenerated),
            groupDate: String(entry?.groupDate || "").trim(),
            previewItems: Array.isArray(entry?.previewItems)
              ? entry.previewItems
                  .map((item) => ({
                    label: String(item?.label || "").trim(),
                    imageUrl: String(item?.imageUrl || "").trim(),
                  }))
                  .filter((item) => item.label)
              : [],
          }))
          .filter((entry) => entry.title && entry.description)
      : [];

    await release.save();
    res.json(formatRelease(release));
  } catch (error) {
    res.status(500).json({ message: error.message || "Could not update release note" });
  }
};

exports.remove = async (req, res) => {
  const { id } = req.params;

  try {
    const release = await Release.findByIdAndDelete(id);

    if (!release) {
      return res.status(404).json({ message: "Release note not found" });
    }

    res.json({ message: "Release note deleted" });
  } catch (error) {
    res.status(500).json({ message: error.message || "Could not delete release note" });
  }
};
